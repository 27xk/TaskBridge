"""Generate TypeScript HTTP wire types from the runtime OpenAPI contract."""

import argparse
import json
from pathlib import Path

from tools.openapi_contract import build_contract_schema

REPO_ROOT = Path(__file__).resolve().parents[2]
TARGET = REPO_ROOT / "desktop/renderer/api/generated-contract.ts"


def typescript_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for union in ("anyOf", "oneOf", "allOf"):
        if union in schema:
            separator = " & " if union == "allOf" else " | "
            return separator.join(typescript_type(item) for item in schema[union])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if properties:
            required = set(schema.get("required", []))
            fields = [
                f"  {json.dumps(name)}{'' if name in required else '?'}: {typescript_type(value)};"
                for name, value in properties.items()
            ]
            return "{\n" + "\n".join(fields) + "\n}"
        additional = schema.get("additionalProperties", True)
        value = typescript_type(additional) if isinstance(additional, dict) else "unknown"
        return f"Record<string, {value}>"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def render_typescript(schema: dict) -> str:
    models = schema.get("components", {}).get("schemas", {})
    header = "// Generated by python -m tools.client_contract --write; do not edit.\n"
    return header + "\n" + "\n\n".join(
        f"export type {name} = {typescript_type(value)};" for name, value in sorted(models.items())
    ) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_typescript(build_contract_schema())
    if args.write:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(rendered, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(REPO_ROOT)}")
        return 0
    if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != rendered:
        print("Client wire contract drift: run python -m tools.client_contract --write")
        return 1
    print("client wire contract check passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
